#!/usr/bin/env python3
"""Check the loader-visible structure of a staged native PS5 title.

This is a host-side structural check, not a console test. It verifies the
FSELF container, the ET_SCE_EXEC_ASLR executable shape, the process-parameter
record, the runtime module, and the presentation metadata.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

FSELF_MAGICS = {0x1D3D154F, 0xEEF51454}
ELF_MAGIC = b"\x7fELF"
PT_LOAD = 1
PT_DYNAMIC = 2
PT_NOTE = 4
PT_SCE_PROCPARAM = 0x61000001
PT_SCE_COMMENT = 0x6FFFFF00
ET_SCE_EXEC_ASLR = 0xFE10

# Generated by the pinned upstream libc-builder and validated by its authors on
# firmware 6.02 and 12.70.  A different hash usually means a user-supplied,
# firmware-matched module, which is the supported override.
DEFAULT_LIBC_SHA256 = "e6ff45d16adf687855cc3b33b0c8a4132b6504360b221e0a34c7e99fb3ba0036"


def u16(data: bytes, at: int) -> int:
    return struct.unpack_from("<H", data, at)[0]


def u32(data: bytes, at: int) -> int:
    return struct.unpack_from("<I", data, at)[0]


def u64(data: bytes, at: int) -> int:
    return struct.unpack_from("<Q", data, at)[0]


def parse_fself(data: bytes, path: Path) -> tuple[int, int]:
    if len(data) < 0x40:
        raise SystemExit(f"{path}: too small for an FSELF")
    magic = u32(data, 0)
    if magic not in FSELF_MAGICS:
        raise SystemExit(f"{path}: not an FSELF (magic 0x{magic:08x})")
    entries = u16(data, 0x18)
    elf_offset = 0x20 + 0x20 * entries
    if elf_offset + 0x40 > len(data):
        raise SystemExit(f"{path}: FSELF segment table overruns the file")
    if data[elf_offset:elf_offset + 4] != ELF_MAGIC:
        raise SystemExit(f"{path}: FSELF does not contain an ELF at 0x{elf_offset:x}")
    return magic, elf_offset


def validate_eboot(path: Path) -> dict:
    data = path.read_bytes()
    magic, elf = parse_fself(data, path)
    if data[elf + 4] != 2 or data[elf + 5] != 1:
        raise SystemExit(f"{path}: inner ELF is not little-endian ELF64")
    if data[elf + 7] != 9:
        raise SystemExit(f"{path}: inner ELF OS/ABI is not FreeBSD (9)")
    if data[elf + 8] != 2:
        raise SystemExit(f"{path}: inner ELF ABI version is not 2")
    e_type = u16(data, elf + 0x10)
    if e_type != ET_SCE_EXEC_ASLR:
        raise SystemExit(f"{path}: inner ELF type is 0x{e_type:04x}, expected 0xfe10")
    entry = u64(data, elf + 0x18)
    if entry == 0:
        raise SystemExit(f"{path}: inner ELF entry point is zero")
    phoff = u64(data, elf + 0x20)
    phentsize = u16(data, elf + 0x36)
    phnum = u16(data, elf + 0x38)
    if phentsize != 0x38:
        raise SystemExit(f"{path}: program-header size is 0x{phentsize:x}, expected 0x38")
    if phnum == 0 or elf + phoff + phentsize * phnum > len(data):
        raise SystemExit(f"{path}: program-header table overruns the file")

    # The FSELF stores selected segments at container offsets, not at the
    # inner ELF's output offsets. Validate the container table separately.
    entries = u16(data, 0x18)
    for index in range(entries):
        at = 0x20 + index * 0x20
        offset = u64(data, at + 0x08)
        size = u64(data, at + 0x10)
        if offset > len(data) or size > len(data) - offset:
            raise SystemExit(f"{path}: FSELF segment {index} overruns the file")

    loads = []
    mapped_loads = 0
    procparam = None
    dynamic = False
    linking_load = False
    for index in range(phnum):
        at = elf + phoff + index * phentsize
        p_type = u32(data, at)
        flags = u32(data, at + 4)
        offset = u64(data, at + 8)
        vaddr = u64(data, at + 16)
        filesz = u64(data, at + 32)
        memsz = u64(data, at + 40)
        align = u64(data, at + 48)
        if p_type == PT_LOAD:
            loads.append((index, flags, vaddr, offset, filesz, memsz, align))
            if flags == 0:
                linking_load = True
            else:
                mapped_loads += 1
            if flags not in (0, 1, 4, 6):
                raise SystemExit(f"{path}: LOAD {index} has unsupported flags 0x{flags:x}")
            if align != 0x4000:
                raise SystemExit(f"{path}: LOAD {index} alignment is 0x{align:x}, expected 0x4000")
            if memsz < filesz:
                raise SystemExit(f"{path}: LOAD {index} memsz is smaller than filesz")
        elif p_type == PT_DYNAMIC:
            dynamic = True
        elif p_type == PT_SCE_PROCPARAM:
            procparam = (offset, filesz)
        elif p_type == PT_SCE_COMMENT:
            if memsz != 0:
                raise SystemExit(f"{path}: comment header has nonzero memsz")
            if align != 0x10:
                raise SystemExit(f"{path}: comment header alignment is 0x{align:x}, expected 0x10")
        elif p_type == PT_NOTE and vaddr == 0 and memsz != 0:
            raise SystemExit(f"{path}: unmapped NOTE header has nonzero memsz")

    if not loads:
        raise SystemExit(f"{path}: no PT_LOAD segments")
    if not linking_load:
        raise SystemExit(f"{path}: no flags-zero linking LOAD")
    if not dynamic:
        raise SystemExit(f"{path}: no PT_DYNAMIC segment")
    if procparam is None:
        raise SystemExit(f"{path}: no PT_SCE_PROCPARAM segment")
    proc_offset, proc_size = procparam
    if proc_size < 0x60:
        raise SystemExit(f"{path}: process-parameter segment is too small")

    return {
        "fself_magic": magic,
        "elf_offset": elf,
        "entry": entry,
        "program_headers": phnum,
        "loads": len(loads),
        "mapped_loads": mapped_loads,
        "procparam": proc_offset,
    }


def png_size(path: Path) -> tuple[int, int]:
    data = path.read_bytes()
    if len(data) < 24 or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        raise SystemExit(f"{path}: not a PNG")
    return struct.unpack(">II", data[16:24])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("title_dir", type=Path)
    args = parser.parse_args()
    title = args.title_dir
    eboot = title / "eboot.bin"
    libc = title / "sce_module/libc.prx"
    param = title / "sce_sys/param.json"
    icon = title / "sce_sys/icon0.png"
    for path in (eboot, libc, param, icon):
        if not path.is_file():
            raise SystemExit(f"{path}: missing")

    info = validate_eboot(eboot)
    libc_data = libc.read_bytes()
    parse_fself(libc_data, libc)
    if not param.read_text(encoding="utf-8").strip():
        raise SystemExit(f"{param}: empty")
    data = json.loads(param.read_text(encoding="utf-8"))
    title_id = data.get("titleId", "")
    if len(title_id) != 9 or not title_id.startswith("PPSA") or not title_id[4:].isdigit():
        raise SystemExit(f"{param}: titleId must be PPSA plus five digits")
    if title_id not in data.get("contentId", ""):
        raise SystemExit(f"{param}: contentId does not contain titleId")
    if int(data.get("downloadDataSize", 0)) <= 0:
        raise SystemExit(f"{param}: downloadDataSize must be positive")
    if png_size(icon) != (512, 512):
        raise SystemExit(f"{icon}: icon0.png must be 512x512")

    print(f"native title OK: {title}")
    print(f"  FSELF magic: 0x{info['fself_magic']:08x}")
    print(f"  inner ELF: 0x{info['elf_offset']:x}, entry 0x{info['entry']:x}")
    print(f"  program headers: {info['program_headers']}, PT_LOAD: {info['loads']}, "
          f"mapped: {info['mapped_loads']}")
    print(f"  process parameters: 0x{info['procparam']:x}")
    print(f"  title: {data['localizedParameters']['en-US']['titleName']} ({title_id})")
    if hashlib.sha256(libc_data).hexdigest() == DEFAULT_LIBC_SHA256:
        print("  note: default clean-room libc.prx; validated on firmware 6.02/12.70.")
        print("        If the title is rejected, use NW_PS5_NATIVE_LIBC with a")
        print("        signed module matching your firmware; see docs/PS5.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
