#!/usr/bin/env python3
"""Central NetWalk application-icon artwork.

This module is the single source of truth for the launcher/window/title icon
used by Android, Windows, Linux, and PS5.  The artwork lives in
``assets/icons/icon.png`` (or ``assets/icon.png``); replace that PNG and
regenerate the checked-in outputs with:

    python3 tools/gen_app_icons.py

The PNG is cropped to its visible alpha bounds and fitted into each requested
size.  Generated icons keep a transparent background so the artwork's alpha
channel is preserved on Android, Windows, Linux, and PS5.  Pillow is required
only when regenerating icons; the release builds use the checked-in outputs and
do not run this module.
"""

from __future__ import annotations

import io
import struct
from functools import lru_cache
from pathlib import Path
from typing import Sequence

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE_CANDIDATES = (
    ROOT / "assets/icons/icon.png",
    ROOT / "assets/icon.png",
)
SIZE = 512
CONTENT_SCALE = 0.94
ALPHA_THRESHOLD = 8


def source_path() -> Path:
    """Return the checked-in source PNG, accepting either supported path."""
    for path in SOURCE_CANDIDATES:
        if path.is_file():
            return path
    candidates = ", ".join(str(path) for path in SOURCE_CANDIDATES)
    raise FileNotFoundError(
        f"NetWalk icon source not found; expected one of: {candidates}")


@lru_cache(maxsize=1)
def _artwork() -> Image.Image:
    """Load the source PNG and crop it to the visible pixels."""
    path = source_path()
    with Image.open(path) as image:
        artwork = image.convert("RGBA")
    alpha = artwork.getchannel("A")
    visible = alpha.point(
        lambda value: 255 if value > ALPHA_THRESHOLD else 0)
    box = visible.getbbox()
    if box is None:
        raise ValueError(f"{path}: icon has no visible pixels")
    return artwork.crop(box)


def _render(size: int, *, background: tuple[int, int, int] | None = None,
            content_scale: float = CONTENT_SCALE,
            round_mask: bool = False) -> Image.Image:
    if size < 1:
        raise ValueError("icon size must be positive")
    if content_scale <= 0:
        raise ValueError("icon content scale must be positive")

    artwork = _artwork()
    fill = (0, 0, 0, 0) if background is None else (*background, 255)
    canvas = Image.new("RGBA", (size, size), fill)

    target = max(1, int(round(size * content_scale)))
    scale = min(target / artwork.width, target / artwork.height)
    width = max(1, int(round(artwork.width * scale)))
    height = max(1, int(round(artwork.height * scale)))
    scaled = artwork.resize((width, height), Image.Resampling.LANCZOS)
    canvas.alpha_composite(scaled, ((size - width) // 2,
                                    (size - height) // 2))

    if round_mask:
        mask = Image.new("L", (size, size), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, size - 1, size - 1), fill=255)
        canvas.putalpha(ImageChops.multiply(canvas.getchannel("A"), mask))
    return canvas


def png_bytes(size: int, *, background: tuple[int, int, int] | None = None,
              content_scale: float = CONTENT_SCALE,
              round_mask: bool = False) -> bytes:
    output = io.BytesIO()
    _render(size, background=background, content_scale=content_scale,
            round_mask=round_mask).save(
                output, format="PNG", optimize=True)
    return output.getvalue()


def write_png(path: Path, size: int, **kwargs) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png_bytes(size, **kwargs))


def write_ico(path: Path,
              sizes: Sequence[int] = (16, 24, 32, 48, 64, 128, 256)) -> None:
    """Write modern PNG-compressed ICO entries.

    Windows Vista and later decode PNG data inside ICO files directly, so the
    original alpha channel survives at every size without flattening the icon
    onto an opaque background.  Keeping the icons in PNG form also avoids the
    much larger legacy DIB payloads.
    """
    images = [png_bytes(size) for size in sizes]
    header = struct.pack("<HHH", 0, 1, len(images))
    entries = bytearray()
    offset = 6 + 16 * len(images)
    for size, data in zip(sizes, images):
        dim = 0 if size >= 256 else size
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32,
                               len(data), offset)
        offset += len(data)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(header + bytes(entries) + b"".join(images))


def write_c_header(path: Path, size: int = 128) -> None:
    data = render_rgba(size)
    lines = [
        "/* Generated by tools/gen_app_icons.py; do not edit by hand. */",
        "#ifndef NW_APP_ICON_H",
        "#define NW_APP_ICON_H",
        "",
        f"#define NW_APP_ICON_WIDTH {size}",
        f"#define NW_APP_ICON_HEIGHT {size}",
        "",
        f"static const unsigned char nw_app_icon_rgba[{len(data)}] = {{",
    ]
    for start in range(0, len(data), 16):
        values = ", ".join(f"0x{value:02x}" for value in data[start:start + 16])
        lines.append(f"    {values},")
    lines.extend(("};", "", "#endif /* NW_APP_ICON_H */", ""))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="ascii")


def render_rgba(size: int, **kwargs) -> bytes:
    return _render(size, **kwargs).tobytes()
